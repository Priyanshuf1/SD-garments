/**
 * ALLEYRICH — Tier 3 Cross-Feature Pairwise Tests: Catalog, Pagination & Cart
 * File: tests/e2e/tier3_pairwise/pairwise_catalog_cart.test.js
 * 
 * Verifies combinatorial interactions between:
 * - F1 (Pagination & Catalog Slicing) + F2 (Category Chips Filtering)
 * - F1 (Pagination & Catalog Slicing) + F5 (Cart Drawer & Quick Buy)
 * - F2 (Category Chips Filtering) + F5 (Cart Drawer & Shipping Progress)
 * - F1 (Pagination) + F9 (Catalog Caching & Response Consistency)
 */

'use strict';

const { defineSuite } = require('../helpers/suite.js');

module.exports = defineSuite({
  tier: 3,
  feature: 'F1+F2+F5+F9',
  title: 'Pairwise: Catalog Slicing, Category Chips & Cart Drawer Interactions',
  description: 'Validates orthogonal feature combinations between storefront browsing, taxonomy filtering, and quick cart operations.'
}, ({ test }) => {

  test('TC-T3-01', 'F1 (Pagination) + F2 (Category Filtering): Slicing and taxonomy category isolation', async ({ client, assert }) => {
    // 1. Fetch total catalog baseline
    const allRes = await client.get('/api/products');
    assert.assertStatus(allRes, 200);
    assert.strictEqual(allRes.data.success, true);
    assert.ok(Array.isArray(allRes.data.products), 'Products should be an array');
    const totalAllCount = allRes.data.products.length;
    assert.ok(totalAllCount > 0, 'Catalog should contain items');

    // 2. Filter by specific category "Top Wear"
    const topWearRes = await client.get('/api/products?category=Top%20Wear');
    assert.assertStatus(topWearRes, 200);
    assert.strictEqual(topWearRes.data.success, true);
    const topWearProducts = topWearRes.data.products;
    assert.ok(Array.isArray(topWearProducts), 'Filtered products should be an array');
    assert.ok(topWearProducts.length > 0, 'Top Wear should have items');
    assert.ok(topWearProducts.length <= totalAllCount, 'Filtered count should be <= total products');

    // Verify all returned products match the category filter
    for (const prod of topWearProducts) {
      const cat = (prod.category || prod.product_type || '').toLowerCase();
      assert.ok(cat.includes('top') || cat.includes('streetwear') || cat.includes('wear'),
        `Product ${prod.id} category (${prod.category}) should match Top Wear filter`);
    }

    // 3. Verify collections.html DOM contracts for category filter resetting pagination
    const pageRes = await client.get('/collections.html');
    assert.assertStatus(pageRes, 200);
    assert.assertHtmlContains(pageRes, 'id="category-chips"', 'Category chips container must exist');
    assert.assertHtmlContains(pageRes, 'catalog-pagination', 'Pagination container must exist');
    assert.assertHtmlContains(pageRes, 'this.pageSize', 'CollectionEngine pageSize must be defined');
    assert.assertHtmlContains(pageRes, 'data-cat=', 'Category chip attributes must exist in DOM');
  });

  test('TC-T3-02', 'F1 (Pagination) + F5 (Cart Quick Add): Adding item from paginated slice to cart', async ({ client, assert }) => {
    // 1. Query catalog
    const catalogRes = await client.get('/api/products');
    assert.assertStatus(catalogRes, 200);
    const products = catalogRes.data.products;
    assert.ok(products.length >= 2, 'Catalog must contain at least 2 products for slicing test');

    // Select an item from index >= 1 (as if on a second slice/page)
    const targetProduct = products[1];
    assert.ok(targetProduct.id, 'Target product must have an ID');
    assert.ok(Number(targetProduct.price) > 0, 'Target product must have a positive price');

    // 2. Validate QuickBuy contract in quick-buy.js
    const quickBuyRes = await client.get('/assets/js/quick-buy.js');
    assert.assertStatus(quickBuyRes, 200);
    assert.assertHtmlContains(quickBuyRes, 'QuickBuy', 'QuickBuy singleton must exist');
    assert.assertHtmlContains(quickBuyRes, 'threshold = 1999', 'Free shipping threshold must be 1999');

    // 3. Emulate cart item structure as generated by QuickBuyEngine
    const variant = targetProduct.variants && targetProduct.variants[0] ? targetProduct.variants[0] : { title: 'M', id: 1 };
    const cartItem = {
      id: String(targetProduct.id),
      handle: targetProduct.handle,
      title: targetProduct.title,
      price: Number(targetProduct.price),
      size: variant.title || 'M',
      quantity: 2,
      image: targetProduct.images && targetProduct.images[0] ? targetProduct.images[0].src : '/images/photo_1.webp'
    };

    // Calculate line total and progress bar
    const lineTotal = cartItem.price * cartItem.quantity;
    assert.strictEqual(lineTotal, Number(targetProduct.price) * 2);

    const shippingThreshold = 1999;
    const progressPercent = Math.min(100, Math.round((lineTotal / shippingThreshold) * 100));
    assert.ok(progressPercent >= 0 && progressPercent <= 100, 'Progress percentage must be between 0 and 100');
  });

  test('TC-T3-03', 'F2 (Category Chips) + F5 (Cart Drawer): Category filtering and cart shipping calculation', async ({ client, assert }) => {
    // 1. Query category "Bottom Wear" or "Jeans"
    const catRes = await client.get('/api/products?category=Bottom%20Wear');
    assert.assertStatus(catRes, 200);
    const bottomWearItems = catRes.data.products;
    assert.ok(Array.isArray(bottomWearItems), 'Bottom Wear products must be an array');
    
    // Choose product
    const product = bottomWearItems[0] || (await client.get('/api/products')).data.products[0];
    const unitPrice = Number(product.price);
    assert.ok(unitPrice > 0, 'Unit price must be positive');

    // Verify Free Shipping calculation for sub-threshold vs qualified
    const singleItemSubtotal = unitPrice;
    const isFreeShippingSingle = singleItemSubtotal >= 1999;
    const expectedRemaining = isFreeShippingSingle ? 0 : 1999 - singleItemSubtotal;

    // Verify calculation math
    if (!isFreeShippingSingle) {
      assert.ok(expectedRemaining > 0, 'Remaining amount must be positive when below ₹1,999');
    }

    // Verify QuickBuy drawer DOM elements in collections.html
    const storefrontRes = await client.get('/collections.html');
    assert.assertStatus(storefrontRes, 200);
    assert.assertHtmlContains(storefrontRes, 'cart-drawer-aside', 'Cart drawer container ID must exist in markup');
    assert.assertHtmlContains(storefrontRes, 'cart-trigger', 'Cart trigger button must exist in markup');
  });

  test('TC-T3-04', 'F1 (Pagination) + F9 (Catalog Caching): Consistent cached response across pagination hits', async ({ client, assert }) => {
    // 1. Hit catalog endpoint 1st time
    const start1 = Date.now();
    const res1 = await client.get('/api/products');
    const time1 = Date.now() - start1;
    assert.assertStatus(res1, 200);
    assert.strictEqual(res1.data.success, true);

    // 2. Hit catalog endpoint 2nd time (should be served from cache or fast in-memory)
    const start2 = Date.now();
    const res2 = await client.get('/api/products');
    const time2 = Date.now() - start2;
    assert.assertStatus(res2, 200);
    assert.strictEqual(res2.data.success, true);

    // Compare counts and first 3 product IDs for deterministic consistency
    assert.strictEqual(res1.data.count, res2.data.count, 'Product count must match between cached calls');
    const slice1 = res1.data.products.slice(0, 5).map(p => p.id);
    const slice2 = res2.data.products.slice(0, 5).map(p => p.id);
    assert.deepStrictEqual(slice1, slice2, 'Product IDs in head slice must match identically');

    // Both calls must complete with healthy latency
    assert.ok(time1 < 2500, `First call should complete in reasonable time (<2500ms), took ${time1}ms`);
    assert.ok(time2 < 2500, `Second call should complete in reasonable time (<2500ms), took ${time2}ms`);
  });

});
